def direct_pdf_repair():
 import sys
 replacements={}
 registry_path=R/'data/seo-books.json'
 registry=json.loads(registry_path.read_text())
 for slug,pdf in DIRECT_PDFS.items():
  path=R/'summaries'/(slug+'.html');s=path.read_text()
  old=re.search(r'<!-- book-landing-route -->(.*?)<!-- /book-landing-route -->',s,re.S)
  assert old,slug
  href=re.search(r'href=["\x27]([^"\x27]+)',old[1]);assert href,slug
  source=unescape(href[1]);replacements[source]=pdf
  def fix_section(m):
   return re.sub(r'<a\b[^>]*>.*?</a>',lambda a: re.sub(r'href=(["\x27]).*?\1','href="'+pdf+'"',a[0],count=1,flags=re.S).replace('اقرأ مجانا لدى المصدر','تحميل PDF مجانا').replace('اقرأ مجانًا لدى المصدر','تحميل PDF مجانا'),m[0],count=1,flags=re.S)
  s=re.sub(r'<!-- book-landing-route -->.*?<!-- /book-landing-route -->',fix_section,s,flags=re.S)
  s=re.sub(r'<section\b[^>]*class=["\x27]book-source["\x27][^>]*>.*?</section>',fix_section,s,flags=re.S)
  path.write_text(s)
  item=next(x for x in registry if x['url']=='summaries/'+slug+'.html')
  item['source_links']=list(dict.fromkeys([pdf]+item.get('source_links',[])))
 for p in list((R/'js').glob('*free*.js'))+[R/'free-books.html']:
  s=p.read_text()
  for old,new in replacements.items():s=s.replace(old,new)
  p.write_text(s)
 registry_path.write_text(json.dumps([b for b in registry if b['url'] not in {x['url'] for q in (R/'data').glob('seo-books-[0-9]*.json') for x in json.loads(q.read_text())}],ensure_ascii=False,indent=2)+'\n')
 print('Repaired',len(DIRECT_PDFS),'verified official direct PDF routes')
